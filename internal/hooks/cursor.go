package hooks

import (
	"encoding/json"
	"fmt"
	"path/filepath"

	"github.com/elionaz/panal/internal/i18n"
	"github.com/elionaz/panal/internal/status"
)

// Cursor CLI (cursor-agent, https://cursor.com/docs/agent/hooks) reads
// hooks.json from ~/.cursor and the project, and from plugins. A local
// plugin can be loaded for one invocation with `--plugin-dir <dir>` (its
// hooks in <dir>/hooks/hooks.json), which is how panal adds its hooks
// without touching either file. As of 2026.11 the CLI runs a plugin's
// sessionStart and tool hooks, but its interactive UI only runs stop and
// beforeSubmitPrompt hooks defined in the user's or the project's
// hooks.json: so the end of a turn is not reported, and the profile keeps
// the heuristic for "working" and "idle". There is no hook for an approval
// prompt either (the profile's attention patterns catch those menus).

// cursorPluginDir is the plugin's directory inside the hooks dir.
const cursorPluginDir = "cursor-plugin"

// cursorEvents are the hooks the plugin registers (see parseCursor).
// stop and beforeSubmitPrompt are listed for when the CLI runs them for
// plugins too.
var cursorEvents = []string{"sessionStart", "beforeSubmitPrompt", "preToolUse", "postToolUse", "postToolUseFailure", "stop"}

func setupCursor(dir, exe, sock string, mcp map[string]MCPServer) (Injection, error) {
	pdir := filepath.Join(dir, cursorPluginDir)
	manifest := []byte(`{"name":"panal","version":"1.0.0","description":"Reports this session's state to panal (generated by panal)."}` + "\n")
	if err := writeIfChanged(filepath.Join(pdir, ".cursor-plugin", "plugin.json"), manifest); err != nil {
		return Injection{}, err
	}
	if err := writeIfChanged(filepath.Join(pdir, "hooks", "hooks.json"), CursorHooks(exe, sock)); err != nil {
		return Injection{}, err
	}
	if err := writeCursorMCP(pdir, mcp); err != nil {
		return Injection{}, err
	}
	return Injection{Args: []string{"--plugin-dir", pdir}, MCP: mcp}, nil
}

// CursorHooks is the plugin's hooks.json: every cursorEvents entry runs
// `<exe> notify [--sock S] --from-hook cursor` (timeouts in seconds). The
// command prints nothing except for sessionStart, so no hook ever answers
// for a permission (empty output is ignored, fail-open).
func CursorHooks(exe, sock string) []byte {
	cmd := hookCommand(exe, sock, AgentCursor)
	type hook struct {
		Command string `json:"command"`
		Timeout int    `json:"timeout"`
	}
	hooks := make(map[string][]hook, len(cursorEvents))
	for _, ev := range cursorEvents {
		to := hookTimeout
		if ev == "preToolUse" {
			to = preToolTimeout
		}
		hooks[ev] = []hook{{Command: cmd, Timeout: to}}
	}
	b, _ := json.MarshalIndent(map[string]any{"version": 1, "hooks": hooks}, "", "  ")
	return append(b, '\n')
}

// cursorPayload holds the fields we use from Cursor hook input. All
// events share conversation_id, generation_id, model and hook_event_name.
type cursorPayload struct {
	HookEventName string          `json:"hook_event_name"`
	ToolName      string          `json:"tool_name"`
	ToolInput     json.RawMessage `json:"tool_input"`
	Status        string          `json:"status"`
}

func parseCursor(data []byte) (status.Event, bool, error) {
	var p cursorPayload
	if err := json.Unmarshal(data, &p); err != nil {
		return status.Event{}, false, fmt.Errorf("cursor hook payload: %w", err)
	}
	switch p.HookEventName {
	case "beforeSubmitPrompt":
		return withActivity(status.Event{State: status.Running, Turn: true}, i18n.ActThinking, ""), true, nil
	case "preToolUse":
		kind, target := ToolActivityParts(canonicalTool(AgentCursor, p.ToolName), p.ToolInput)
		return withActivity(status.Event{State: status.Running}, kind, target), true, nil
	case "postToolUse", "postToolUseFailure":
		return status.Event{State: status.Running}, true, nil
	case "stop":
		switch p.Status {
		case "error":
			return status.Event{State: status.Idle, Kind: status.KindError}, true, nil
		case "aborted":
			return status.Event{State: status.Idle, Kind: status.KindDone, Message: "Interrupted"}, true, nil
		}
		return status.Event{State: status.Idle, Kind: status.KindDone}, true, nil
	}
	return status.Event{}, false, nil
}
