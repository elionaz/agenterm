// opencode (v2, https://opencode.ai/docs/build/plugins/server/) has no
// hook commands: plugins run inside its server and read its event stream.
// panal generates a small plugin in the hooks dir that forwards the events
// it cares about to `notify --from-hook opencode`, one at a time and in
// order, as JSON on stdin (opencodePayload). The plugin is loaded through
// OPENCODE_CONFIG_CONTENT, an extra config document merged over the user's
// and the project's (whose `plugins` and `instructions` lists add up);
// `--standalone` gives the session a private server that inherits that
// environment (by default opencode 2 talks to a shared background service,
// started with its own environment, which would never see it).

const (
	// opencodeConfigEnv carries an inline config document.
	opencodeConfigEnv = "OPENCODE_CONFIG_CONTENT"
	// opencodePluginDir is the plugin's directory inside the hooks dir
	// (opencode loads local plugins from a directory's index.js).
	opencodePluginDir = "opencode-plugin"
)

// setupOpencode writes the plugin and returns the flag and environment
// that load it.
func setupOpencode(dir, exe, sock string) (Injection, error) {
	if os.Getenv(opencodeConfigEnv) != "" {
		// The user's own inline config would be replaced.
		return Injection{Note: "opencode hooks off: " + opencodeConfigEnv + " is already set"}, nil
	}
	pdir := filepath.Join(dir, opencodePluginDir)
	if err := writeIfChanged(filepath.Join(pdir, "index.js"), OpencodePlugin(exe, sock)); err != nil {
		return Injection{}, err
	}
	return Injection{
		Args: []string{"--standalone"},
		Env:  []string{OpencodeConfigEnv(pdir, "")},
	}, nil
}

// OpencodeConfigEnv is the OPENCODE_CONFIG_CONTENT=… entry loading the
// plugin in pluginDir and, when instructions is a file, adding it to the
// session's instructions.
func OpencodeConfigEnv(pluginDir, instructions string) string {
	cfg := map[string]any{"plugins": []any{map[string]any{"package": pluginDir}}}
	if instructions != "" {
		cfg["instructions"] = []string{instructions}
	}
	b, _ := json.Marshal(cfg)
	return opencodeConfigEnv + "=" + string(b)
}

// OpencodeInstructionsEnv is the OPENCODE_CONFIG_CONTENT=… entry for a
// session of an opencode profile set up in dir whose instructions are in
// the file instructions; "" when the integration is off (inj has no
// such entry).
func OpencodeInstructionsEnv(inj Injection, dir, instructions string) string {
	for _, kv := range inj.Env {
		if strings.HasPrefix(kv, opencodeConfigEnv+"=") {
			return OpencodeConfigEnv(filepath.Join(dir, opencodePluginDir), instructions)
		}
	}
	return ""
}

// opencodeEvents are the event types the plugin subscribes to.
var opencodeEvents = []string{
	"session.created",
	"session.execution.started", "session.execution.succeeded", "session.execution.failed", "session.execution.interrupted",
	"session.tool.input.started", "session.tool.called",
	"session.step.started", "session.model.selected",
	"permission.asked", "permission.replied",
	"form.created", "form.replied", "form.cancelled",
}

// OpencodePlugin is the plugin's index.js. Subagent sessions (created
// with a parentID) only forward what waits for the user (permissions,
// forms), reported for the session they belong to; their turns are not
// the conversation's.
func OpencodePlugin(exe, sock string) []byte {
	argv, _ := json.Marshal(append(notifyArgv(exe, sock), "--from-hook", AgentOpencode))
	types, _ := json.Marshal(opencodeEvents)
	return []byte(`// Generated by panal for the opencode sessions it launches: reports their
// state to panal (panal notify --from-hook opencode). Rewritten at each launch.
import { spawn } from "node:child_process"

const ARGV = ` + string(argv) + `
const TYPES = ` + string(types) + `
const parents = new Map() // subagent session -> parent session
const tools = new Map() // tool call id -> tool name
const models = new Map() // session -> last model reported
let queue = Promise.resolve()

function root(id) {
  for (let i = 0; i < 16 && parents.has(id); i++) id = parents.get(id)
  return id
}

// send runs notify with ev on stdin, after the previous one has finished,
// so panal gets the events in order.
function send(ev) {
  if (!process.env.PANAL_SESSION) return
  queue = queue.then(() => new Promise((done) => {
    try {
      const p = spawn(ARGV[0], ARGV.slice(1), { stdio: ["pipe", "ignore", "ignore"] })
      const timer = setTimeout(() => { try { p.kill() } catch {} done() }, 5000)
      p.on("error", () => { clearTimeout(timer); done() })
      p.on("exit", () => { clearTimeout(timer); done() })
      p.stdin.on("error", () => {})
      p.stdin.end(JSON.stringify(ev))
    } catch {
      done()
    }
  }))
}

function handle(e) {
  const d = (e && e.data) || {}
  const type = e && e.type
  if (type === "session.created" && d.parentID) {
    parents.set(d.sessionID, d.parentID)
    return
  }
  if (type === "session.tool.input.started") {
    tools.set(d.id, d.name)
    return
  }
  const sid = type && type.startsWith("form.") && d.form ? d.form.sessionID : d.sessionID
  if (!sid) return
  const sub = parents.has(sid)
  const waits = type.startsWith("permission.") || type.startsWith("form.")
  if (sub && !waits) return
  const out = { event: type, sessionID: root(sid) }
  switch (type) {
    case "session.created":
    case "session.step.started":
    case "session.model.selected": {
      const m = d.model && d.model.id
      if (type !== "session.created" && (!m || models.get(out.sessionID) === m)) return
      if (m) {
        models.set(out.sessionID, m)
        out.model = m
      }
      break
    }
    case "session.tool.called":
      out.tool = tools.get(d.id) || ""
      out.input = d.input || {}
      tools.delete(d.id)
      break
    case "session.execution.failed":
      out.error = (d.error && d.error.message) || ""
      break
    case "session.execution.interrupted":
      out.reason = d.reason || ""
      break
    case "permission.asked":
      out.action = d.action || ""
      out.resources = (d.resources || []).slice(0, 3)
      out.message = d.message || ""
      break
    case "form.created":
      out.title = (d.form && d.form.title) || ""
      break
  }
  send(out)
}

export default {
  id: "panal",
  setup(ctx) {
    const controller = new AbortController()
    void (async () => {
      try {
        for await (const e of ctx.event.subscribe({ types: TYPES, signal: controller.signal })) handle(e)
      } catch {}
    })()
    return () => controller.abort()
  },
}
`)
}

// opencodePayload is what the plugin sends for an event.
type opencodePayload struct {
	Event     string          `json:"event"`
	SessionID string          `json:"sessionID"`
	Model     string          `json:"model"`
	Tool      string          `json:"tool"`
	Input     json.RawMessage `json:"input"`
	Error     string          `json:"error"`
	Reason    string          `json:"reason"`
	Action    string          `json:"action"`
	Resources []string        `json:"resources"`
	Message   string          `json:"message"`
	Title     string          `json:"title"`
}

// parseOpencode maps the plugin's events to states. An execution is a
// turn: it starts, and it succeeds, fails or is interrupted.
func parseOpencode(data []byte) (status.Event, bool, error) {
	var p opencodePayload
	if err := json.Unmarshal(data, &p); err != nil {
		return status.Event{}, false, fmt.Errorf("opencode plugin payload: %w", err)
	}
	switch p.Event {
	case "session.execution.started":
		return withActivity(status.Event{State: status.Running, Turn: true}, i18n.ActThinking, ""), true, nil
	case "session.tool.called":
		kind, target := ToolActivityParts(canonicalTool(AgentOpencode, p.Tool), p.Input)
		return withActivity(status.Event{State: status.Running}, kind, target), true, nil
	case "permission.asked":
		msg := p.Message
		if msg == "" {
			msg = p.Action
			if len(p.Resources) > 0 {
				msg += ": " + strings.Join(p.Resources, ", ")
			}
		}
		return status.Event{State: status.WaitingInput, Kind: status.KindPermission, Message: clip(msg)}, true, nil
	case "form.created":
		return status.Event{State: status.WaitingInput, Kind: status.KindQuestion, Message: clip(p.Title)}, true, nil
	case "permission.replied", "form.replied", "form.cancelled":
		return status.Event{State: status.Running}, true, nil
	case "session.execution.succeeded":
		return status.Event{State: status.Idle, Kind: status.KindDone}, true, nil
	case "session.execution.failed":
		return status.Event{State: status.Idle, Kind: status.KindError, Message: clip(p.Error)}, true, nil
	case "session.execution.interrupted":
		// superseded: a new prompt took over (its own execution follows);
		// shutdown: the process is going away.
		if p.Reason == "user" || p.Reason == "inactivity" {
			return status.Event{State: status.Idle, Kind: status.KindDone, Message: "Interrupted"}, true, nil
		}
	}
	return status.Event{}, false, nil
}

// opencodeMinMajor is the first opencode release with the plugin API and
// the --standalone flag the integration uses.
const opencodeMinMajor = 2

var (
	ocMu    sync.Mutex
	ocCache = map[string]ocVersion{}
)

type ocVersion struct {
	mod time.Time
	ok  bool
}

var versionRe = regexp.MustCompile(`(\d+)\.(\d+)\.(\d+)`)

// OpencodeSupported reports whether the opencode binary at path (absolute,
// or looked up in PATH) is a release the integration works with (2.x and
// later). It runs `<path> --version` once per binary (and modification
// time); an unknown answer counts as unsupported.
func OpencodeSupported(path string) bool {
	if p, err := exec.LookPath(path); err == nil {
		path = p
	}
	fi, err := os.Stat(path)
	if err != nil {
		return false
	}
	ocMu.Lock()
	if v, ok := ocCache[path]; ok && v.mod.Equal(fi.ModTime()) {
		ocMu.Unlock()
		return v.ok
	}
	ocMu.Unlock()
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, path, "--version").Output()
	ok := err == nil && opencodeVersionOK(string(out))
	ocMu.Lock()
	ocCache[path] = ocVersion{mod: fi.ModTime(), ok: ok}
	ocMu.Unlock()
	return ok
}

func opencodeVersionOK(s string) bool {
	m := versionRe.FindStringSubmatch(s)
	if m == nil {
		return false
	}
	major, _ := strconv.Atoi(m[1])
	return major >= opencodeMinMajor
}
